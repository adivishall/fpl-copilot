"use client";

import { useState } from "react";

import { Markdown } from "@/components/markdown";
import { Card, PageHeader, State, useApi } from "@/components/ui";
import { apiUrl } from "@/lib/api";

interface Report {
  name: string;
  markdown: string;
  data: Record<string, unknown> | null;
}

const TABS: [string, string][] = [
  ["backtest", "Walk-forward backtest"],
  ["forecast_eval", "Forecast evaluation & calibration"],
  ["optimizer_benchmark", "Optimiser benchmark"],
  ["price_change", "Price-change model"],
  ["baselines", "Baselines"],
  ["rate_shrinkage", "Rate shrinkage"],
  ["feature_importance", "Feature importance"],
  ["ensemble_conformal", "Ensemble & conformal (P1)"],
];

export default function BacktestLab() {
  const [tab, setTab] = useState("backtest");
  const rep = useApi<Report>(`/reports/${tab}`, [tab]);
  return (
    <>
      <PageHeader title="Backtest Lab" lede={<>Published, reproducible reports on the past seasons (generated by <code>ml/experiments/*</code>; successes and failures included). This season&apos;s live forecasts are judged in the Season Review.</>} />
      <div className="tabs">
        {TABS.map(([k, label]) => (
          <button key={k} className={tab === k ? "on" : ""} onClick={() => setTab(k)} aria-pressed={tab === k}>{label}</button>
        ))}
      </div>
      <Card testId="report" wide>
        <State loading={rep.loading} error={rep.error} retry={rep.reload} />
        {/* figures are shown where the report references them (no separate list to drift) */}
        {rep.data ? <Markdown text={rep.data.markdown} figure={(f) => apiUrl(`/reports/figures/${encodeURIComponent(f)}`)} /> : null}
      </Card>
    </>
  );
}
